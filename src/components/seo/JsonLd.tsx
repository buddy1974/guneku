/* Structured data built only from fields the records actually carry.
   No date, author or entity is fabricated to satisfy a schema. */
export function JsonLd({ data }: { data: Record<string, unknown> }) {
  return (
    <script
      type="application/ld+json"
      dangerouslySetInnerHTML={{ __html: JSON.stringify(data) }}
    />
  )
}
